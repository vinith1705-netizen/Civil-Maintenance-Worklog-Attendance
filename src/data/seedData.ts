// Helper to determine base wage based on worker designation
const getBaseWage = (designation: string): number => {
  if (designation.includes('Tiles Mason')) return 900;
  if (designation.includes('Mason') && !designation.includes('Helper')) return 850;
  if (designation.includes('Carpentry') || designation.includes('Carpenter') && !designation.includes('Helper')) return 850;
  if (designation.includes('Welder')) return 850;
  if (designation.includes('Stone Cutter')) return 800;
  if (designation.includes('Polisher Grade I')) return 800;
  if (designation.includes('Polisher Grade II')) return 750;
  if (designation.includes('Polisher Helper')) return 600;
  if (designation.includes('Mason Helper') || designation.includes('Carpenter Helper')) return 650;
  if (designation.includes('Women Mazdoor')) return 550;
  if (designation.includes('Helper')) return 600;
  return 700;
};

